data class MujKalendar(
    val id: Long,
    val name: String,
    val platformId: String = id.toString()
) {
    override fun toString(): String = name
}

data class Udalost(
    val instanceId: Long,
    val eventId: Long,
    val title: String,
    val beginTime: Long,
    val calendarId: Long,
    val rrule: String?,
    val allDay: Boolean,
    val allDayString: String,
    val platformId: String = eventId.toString()
) {
    fun formatRadek(): String {
        if (allDay) return "$allDayString  -  $title"
        val dt = CalendarBridge.extractDateTime(beginTime)
        val hh = dt.hour.toString().padStart(2, '0')
        val mm = dt.minute.toString().padStart(2, '0')
        return "$hh:$mm  -  $title"
    }
}

